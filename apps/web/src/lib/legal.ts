function contactLines(): string[] {
  return [
    OPERATOR.name ? `${OPERATOR.status ? `${capital(OPERATOR.status)}: ` : ""}${OPERATOR.name}` : `Администрация сервиса ${SITE.name}`,
    ...(OPERATOR.inn ? [`ИНН: ${OPERATOR.inn}`] : []),
    ...(OPERATOR.ogrn ? [`ОГРН/ОГРНИП: ${OPERATOR.ogrn}`] : []),
    ...(OPERATOR.address ? [`Адрес для корреспонденции: ${OPERATOR.address}`] : []),
    `Электронная почта: ${OPERATOR.email}`,
    `Сайт: ${SITE.url}`,
  ];
}

function capital(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** Consent to payment terms given in this browser, for this edition. */
const PAY_KEY = "as:pay-consent";
export function payConsentGiven(): boolean {
  try {
    return localStorage.getItem(PAY_KEY) === LEGAL_VERSION;
  } catch {
    return false;
  }
}
export function givePayConsent(): void {
  try {
    localStorage.setItem(PAY_KEY, LEGAL_VERSION);
  } catch {
    // No storage: asked again next time.
  }
}
